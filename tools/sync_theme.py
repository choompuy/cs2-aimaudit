#!/usr/bin/env python3
"""
Regenerate the theme parts of .streamlit/config.toml from theme/tokens.toml.

Run from the repo root (after editing tokens):

    python tools/sync_theme.py            # active theme (env, default violet)
    AIMAUDIT_THEME=green python tools/sync_theme.py

What it owns in .streamlit/config.toml (and rewrites):
- the whole [theme] section (colours, baseRadius, font, chart palette)
- every [[theme.fontFaces]] table (local fonts from static/fonts/)
- server.enableStaticServing = true   (required to serve those fonts)

Everything else — comments, [browser], [server] upload limits — is kept
byte-for-byte. tests/check_ui.py verifies the file matches the tokens, so a
hand edit of the [theme] section is caught instead of silently drifting.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import theme  # noqa: E402  (needs ROOT on sys.path)
from theme.loader import config_theme_dict, font_faces  # noqa: E402

CONFIG = ROOT / ".streamlit" / "config.toml"


def _tv(value) -> str:
    """Render a Python value as a TOML value (strings as basic strings)."""
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def theme_block_lines() -> list[str]:
    """The generated [theme] body (without the section header) + fontFaces."""
    cfg = config_theme_dict()
    lines = [
        "# Generated by tools/sync_theme.py from theme/tokens.toml —",
        "# do not edit here: change the tokens and re-run the tool.",
    ]
    for key in (
        "base",
        "primaryColor",
        "backgroundColor",
        "secondaryBackgroundColor",
        "textColor",
        "borderColor",
        "baseRadius",
        "font",
    ):
        lines.append(f"{key} = {_tv(cfg[key])}")
    palette = ", ".join(_tv(c) for c in cfg["chartCategoricalColors"])
    lines.append(f"chartCategoricalColors = [{palette}]")
    for face in font_faces():
        lines += [
            "",
            "[[theme.fontFaces]]",
            f"family = {_tv(face['family'])}",
            f"url = {_tv(face['url'])}",
        ]
        if face.get("weight"):
            lines.append(f"weight = {_tv(face['weight'])}")
        if face.get("style"):
            lines.append(f"style = {_tv(face['style'])}")
    return lines


def _sections(text: str):
    """Split config text into (header, lines) blocks; header None = preamble."""
    blocks: list[tuple[str | None, list[str]]] = [(None, [])]
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            blocks.append((stripped, []))
        else:
            blocks[-1][1].append(line)
    return blocks


def _ensure_static_serving(lines: list[str], needed: bool) -> list[str]:
    """Add, update or drop the enableStaticServing line (sync owns the key)."""
    if needed:
        out, seen = [], False
        for line in lines:
            if line.strip().startswith("enableStaticServing"):
                out.append("enableStaticServing = true")
                seen = True
            else:
                out.append(line)
        if not seen:
            out.append("enableStaticServing = true")
        return out
    return [
        line for line in lines if not line.strip().startswith("enableStaticServing")
    ]


def sync() -> None:
    if not CONFIG.exists():
        raise SystemExit(f"missing {CONFIG}")
    blocks = _sections(CONFIG.read_text(encoding="utf-8"))
    faces = font_faces()
    new_theme = theme_block_lines()

    out: list[tuple[str | None, list[str]]] = []
    theme_inserted = False
    for header, lines in blocks:
        if header in ("[theme]", "[[theme.fontFaces]]"):
            if not theme_inserted:  # first old theme block marks the spot
                out.append(("[theme]", new_theme))
                theme_inserted = True
            continue  # drop every old theme-owned block
        if header == "[server]":
            lines = _ensure_static_serving(lines, needed=bool(faces))
        out.append((header, lines))
    if not theme_inserted:  # config had no [theme] at all: put it on top
        out.insert(0, ("[theme]", new_theme))

    parts: list[str] = []
    for header, lines in out:
        if header is None and not any(ln.strip() for ln in lines):
            continue  # skip an empty preamble
        body = "\n".join(lines).rstrip("\n")
        block = f"{header}\n{body}".rstrip("\n") if body else (header or "")
        parts.append(block)
    CONFIG.write_text("\n\n".join(parts) + "\n", encoding="utf-8")

    print(f"synced {CONFIG.relative_to(ROOT)} for theme '{theme.active_theme()}'")
    cfg = config_theme_dict()
    print(f"  primaryColor   {cfg['primaryColor']}")
    print(f"  background     {cfg['backgroundColor']}")
    print(f"  font           {cfg['font']} ({len(faces)} local fontFaces)")
    print("restart the app (start.sh / start.bat) to see the change")


if __name__ == "__main__":
    sync()
