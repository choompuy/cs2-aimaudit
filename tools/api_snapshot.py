"""Snapshot of the ``core`` top-level API.

Writes a sorted list of every top-level name ``core`` defines, annotated
with the consumers that reference it (app.py, tests/, tools/). Used to
verify the ``core/`` package exposes every name its consumers use.

Usage: python tools/api_snapshot.py [--out FILE]
"""

from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Files outside core that are allowed to reference core names.
CONSUMERS = [
    "app.py",
    "mapview.py",
    "store.py",
    "i18n.py",
    "tools/inspect_rounds.py",
    "tools/fetch_radars.py",
    "tools/sync_theme.py",
    "tools/dump_payloads.py",
    "tests/test_core.py",
    "tests/smoke_app.py",
    "tests/check_ui.py",
]


def _top_names(src: str, out: dict[str, str]) -> None:
    for node in ast.parse(src).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            out[node.name] = "def"
        elif isinstance(node, ast.ClassDef):
            out[node.name] = "class"
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    out[t.id] = "var"
                elif isinstance(t, (ast.Tuple, ast.List)):
                    for e in t.elts:
                        if isinstance(e, ast.Name):
                            out[e.id] = "var"
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            out[node.target.id] = "var"
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            # imports must not overwrite a def/var recorded from another
            # module of the package (e.g. replay.py re-imports apply_filters)
            for a in node.names:
                out.setdefault((a.asname or a.name).split(".")[0], "import")


def core_names() -> dict[str, str]:
    """Top-level names of core -> definition kind.

    Works both for the old single module (core.py) and for the core/
    package (union of the per-module top-level names).
    """
    out: dict[str, str] = {}
    # a core/ package shadows a same-named core.py module, so the package
    # wins when both exist (that is what `import core` resolves to)
    if (ROOT / "core").is_dir():
        # __init__.py is a pure re-export facade: skip it, its from-imports
        # would mark every re-exported name as "import"
        for path in sorted((ROOT / "core").glob("*.py")):
            if path.name == "__init__.py":
                continue
            out.setdefault(path.stem, "module")
            _top_names(path.read_text(encoding="utf-8"), out)
    else:
        _top_names((ROOT / "core.py").read_text(encoding="utf-8"), out)
    return out


def consumer_usage() -> dict[str, set[str]]:
    """core.X attribute references per consumer file."""
    usage: dict[str, set[str]] = {}
    for rel in CONSUMERS:
        path = ROOT / rel
        if not path.exists():
            continue
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        names: set[str] = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
                if node.value.id == "core":
                    names.add(node.attr)
        usage[rel] = names
    return usage


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="-")
    args = ap.parse_args()

    names = core_names()
    usage = consumer_usage()
    used: set[str] = set()
    for refs in usage.values():
        used |= refs

    lines = ["# core API snapshot (generated by tools/api_snapshot.py)"]
    for name in sorted(names):
        kind = names[name]
        who = sorted(f for f, refs in usage.items() if name in refs)
        note = f"  # used by: {', '.join(who)}" if who else ""
        lines.append(f"{kind:<6} {name}{note}")
    missing = sorted(used - set(names))
    if missing:
        lines.append(f"# !! referenced but not defined in core: {missing}")

    # package form: every name must also be reachable through the facade
    if not (ROOT / "core.py").exists():
        import sys

        if str(ROOT) not in sys.path:
            sys.path.insert(0, str(ROOT))
        import core  # noqa: E402

        unreachable = sorted(n for n in names if not hasattr(core, n))
        if unreachable:
            lines.append(f"# !! NOT re-exported by the core facade: {unreachable}")

    text = "\n".join(lines) + "\n"
    if args.out == "-":
        print(text)
    else:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"{len(names)} names -> {args.out}")


if __name__ == "__main__":
    main()
